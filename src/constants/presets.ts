export function getSmartChannelSuggestions(currentChannels: Channel[]): Array<
  SimilarChannelSuggestion & {
    isAdded: boolean;
    reasonText: string;
    matchedChannels: string[];
    score: number;
  }
> {
  const currentIds = new Set(currentChannels.map(c => c.id));
  const currentTitles = currentChannels.map(c => (c.title || '').toLowerCase());
  const categoryCounts = currentChannels.reduce<Record<string, number>>((acc, c) => {
    if (c.categoryId) acc[c.categoryId] = (acc[c.categoryId] || 0) + 1;
    return acc;
  }, {});

  return SIMILAR_SUGGESTIONS.map(sug => {
    const isAdded = currentIds.has(sug.id) || currentChannels.some(c => c.handle && c.handle.toLowerCase() === sug.handle.toLowerCase());

    const matched = sug.reasons.filter(reason =>
      currentTitles.some(t => t.includes(reason.toLowerCase()))
    );

    let score = 0;
    if (matched.length > 0) score += matched.length * 15;
    if (sug.categoryId && categoryCounts[sug.categoryId]) {
      score += categoryCounts[sug.categoryId] * 3;
    }

    let reasonText = '';
    if (matched.length > 0) {
      if (matched.length === 1) {
        reasonText = `Porque você autorizou "${matched[0]}"`;
      } else {
        reasonText = `Porque você autorizou "${matched.slice(0, 2).join('" e "')}"`;
      }
    } else if (sug.categoryId && categoryCounts[sug.categoryId]) {
      reasonText = `Muito popular entre canais desta categoria`;
    } else {
      reasonText = `Conteúdo infantil educativo e seguro`;
    }

    return {
      ...sug,
      isAdded,
      reasonText,
      matchedChannels: matched,
      score,
    };
  }).sort((a, b) => {
    if (a.isAdded !== b.isAdded) return a.isAdded ? 1 : -1;
    return b.score - a.score;
  });
}

